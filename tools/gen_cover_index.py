#!/usr/bin/env python3
"""Regenerates host/cdi_boxarts.h: the file names of the box art in the
libretro-thumbnails 'Philips - CD-i' set, with each picture's git blob id (SHA-1).

The launcher downloads only the pictures it needs, and uses the ids to check that
what arrived is exactly the file in this list, whatever the connection or TLS
setup it came through. Names and ids only: no pictures are stored here.

    python3 tools/gen_cover_index.py     # needs the network (GitHub API, or git)
"""
import json
import os
import subprocess
import sys
import tempfile
import urllib.request

REPO = "libretro-thumbnails/Philips_-_CD-i"


def from_api():
    req = urllib.request.Request("https://api.github.com/repos/%s/git/trees/master?recursive=1" % REPO,
                                 headers={"User-Agent": "ps5-cdi-gen-cover-index/1.0"})
    data = json.loads(urllib.request.urlopen(req, timeout=40).read().decode())
    if data.get("truncated"):
        raise RuntimeError("file list truncated")
    return {t["path"].split("/", 1)[1]: t["sha"] for t in data["tree"]
            if t["path"].startswith("Named_Boxarts/") and t["path"].lower().endswith(".png")}


def from_git():
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(["git", "clone", "-q", "--depth", "1", "--filter=blob:none", "--no-checkout",
                        "https://github.com/" + REPO, tmp + "/r"], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        out = subprocess.run(["git", "-C", tmp + "/r", "ls-tree", "-r", "HEAD"], check=True,
                             capture_output=True, text=True).stdout
    res = {}
    for line in out.splitlines():
        meta, path = line.split("\t", 1)
        if path.startswith("Named_Boxarts/") and path.lower().endswith(".png"):
            res[path.split("/", 1)[1]] = meta.split()[2]
    return res


entries = None
errors = []
for label, fn in (("GitHub API", from_api), ("git", from_git)):
    try:
        entries = fn()
        if entries:
            break
    except Exception as e:  # noqa: BLE001
        errors.append("%s: %s" % (label, e))
if not entries:
    sys.exit("Could not get the file list:\n  " + "\n  ".join(errors))

names = sorted(entries, key=str.lower)
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "host", "cdi_boxarts.h")
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/gen_cover_index.py from\n")
    f.write(" * https://github.com/libretro-thumbnails/Philips_-_CD-i (Named_Boxarts): the file names\n")
    f.write(" * and each picture's git blob id (SHA-1 of \"blob <size>\\0<content>\"). No pictures. */\n")
    f.write("static const struct { const char *name; unsigned char sha1[20]; } cdi_boxart_list[] = {\n")
    for n in names:
        esc = n.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?")
        sha = bytes.fromhex(entries[n])
        f.write('    {"%s", {%s}},\n' % (esc, ",".join("0x%02x" % b for b in sha)))
    f.write("};\n#define CDI_BOXARTS_COUNT %d\n" % len(names))
print("wrote %s (%d names)" % (os.path.normpath(out), len(names)))
