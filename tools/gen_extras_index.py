#!/usr/bin/env python3
"""Regenerates host/cdi_extras.h: the in-game screenshots (Named_Snaps, the game card's backdrop) and the game logos
(Named_Logos, the card's title) of the libretro-thumbnails 'Philips - CD-i' set, with each picture's git blob id
(SHA-1), as host/cdi_boxarts.h does for the box art (tools/gen_cover_index.py).

The title downloads one game's pictures when its card is opened, and checks each against its id. Names and ids
only: no pictures are stored here.

    python3 tools/gen_extras_index.py     # needs git and GitHub
"""
import os
import subprocess
import sys
import tempfile

REPO = "libretro-thumbnails/Philips_-_CD-i"
FOLDERS = (("Named_Snaps", "cdi_snap_list", "CDI_SNAPS_COUNT"), ("Named_Logos", "cdi_logo_list", "CDI_LOGOS_COUNT"))

tmp_holder = tempfile.TemporaryDirectory()
tmp = tmp_holder.name
tmp_dir = tmp + "/r"
if True:
    try:
        subprocess.run(["git", "clone", "-q", "--depth", "1", "--filter=blob:none", "--no-checkout",
                        "https://github.com/" + REPO, tmp + "/r"], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        out = subprocess.run(["git", "-C", tmp + "/r", "ls-tree", "-r", "HEAD"], check=True,
                             capture_output=True, text=True).stdout
        rev = subprocess.run(["git", "-C", tmp + "/r", "rev-parse", "--short=12", "HEAD"], check=True,
                             capture_output=True, text=True).stdout.strip()
    except subprocess.CalledProcessError as e:
        sys.exit("Could not get the file list: %s" % e)

# Many logos are symbolic links to another logo (one picture for several regions). GitHub serves a link as the
# name it points to, not the picture: each link is followed (in the same folder) to the file it names, and the
# entry keeps its own name (for matching games) with that file's name and id (for the download and its check).
entries = {}   # path -> (mode, id)
for line in out.splitlines():
    meta, path = line.split("\t", 1)
    mode, _, oid = meta.split()
    entries[path] = (mode, oid)

def target_of(oid):
    return subprocess.run(["git", "-C", tmp_dir, "cat-file", "-p", oid], check=True, capture_output=True,
                          text=True).stdout.strip()

def resolve(path):
    seen = set()
    while path in entries and entries[path][0] == "120000":
        if path in seen or len(seen) > 8:
            return None
        seen.add(path)
        target = target_of(entries[path][1])
        path = os.path.normpath(os.path.join(os.path.dirname(path), target))
    return path if path in entries else None

lists = {folder: {} for folder, _, _ in FOLDERS}
links = 0
for path, (mode, oid) in entries.items():
    folder, _, name = path.partition("/")
    if folder not in lists or not name.lower().endswith(".png"):
        continue
    real = resolve(path) if mode == "120000" else path
    if not real:
        continue
    if mode == "120000":
        links += 1
    rfolder, _, rname = real.partition("/")
    if rfolder != folder:
        continue  # (none point outside their folder; skipped if one ever does)
    lists[folder][name] = (rname, entries[real][1])

dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "host", "cdi_extras.h")
with open(dest, "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/gen_extras_index.py from\n")
    f.write(" * https://github.com/%s at %s (Named_Snaps, Named_Logos): the file names\n" % (REPO, rev))
    f.write(" * names (to match games by), the file each one is (a symbolic link followed to the picture it names) and\n")
    f.write(" * that picture's git blob id (SHA-1 of \"blob <size>\\0<content>\"). No pictures. */\n")
    for folder, var, count in FOLDERS:
        names = sorted(lists[folder], key=str.lower)
        f.write("static const struct { const char *name; const char *file; unsigned char sha1[20]; } %s[] = {\n" % var)
        for n in names:
            esc = lambda v: v.replace("\\", "\\\\").replace('"', '\\"').replace("?", "\\?")
            rname, oid = lists[folder][n]
            sha = bytes.fromhex(oid)
            f.write('    {"%s", "%s", {%s}},\n' % (esc(n), esc(rname), ",".join("0x%02x" % b for b in sha)))
        f.write("};\n#define %s %d\n" % (count, len(names)))
print("wrote %s (%s; %d links followed)" % (os.path.normpath(dest), ", ".join("%s %d" % (k, len(v)) for k, v in lists.items()), links))
tmp_holder.cleanup()
