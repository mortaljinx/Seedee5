#!/usr/bin/env python3
"""Generates host/font8x16.h (ASCII 0x20-0x7E, 8x16 cells, 1 bit per pixel) from
the Terminus font (SIL Open Font License 1.1, (c) Dimitar Toshkov Zhekov).
Run once on a machine with Pillow and fonts-terminus installed; the generated
header is checked in, so building the host needs neither."""
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/terminus/TerminusTTF-4.46.0.ttf"
font = ImageFont.truetype(FONT, 16)
rows = []
for code in range(0x20, 0x7F):
    img = Image.new("1", (8, 16), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((0, 0), chr(code), font=font, fill=1)
    px = img.load()
    rows.append([sum((1 << (7 - x)) for x in range(8) if px[x, y]) for y in range(16)])

with open("host/font8x16.h", "w") as f:
    f.write("/* 8x16 bitmap font, ASCII 0x20-0x7E, generated by tools/gen_font.py.\n")
    f.write(" * Glyphs rasterised from Terminus, (c) Dimitar Toshkov Zhekov, SIL Open Font\n")
    f.write(" * License 1.1 (https://scripts.sil.org/OFL). */\n")
    f.write("static const unsigned char font8x16[95][16] = {\n")
    for code, r in zip(range(0x20, 0x7F), rows):
        f.write("    {" + ",".join("0x%02x" % b for b in r) + "}, /* '%s' */\n" % (chr(code) if chr(code) not in "\\'" else "\\" + chr(code)))
    f.write("};\n")

# contact sheet for checking by eye
sheet = Image.new("L", (8 * 16 * 3, 16 * 6 * 3), 0)
for i, r in enumerate(rows):
    cx, cy = (i % 16) * 8 * 3, (i // 16) * 16 * 3
    for y in range(16):
        for x in range(8):
            if r[y] & (0x80 >> x):
                for dy in range(3):
                    for dx in range(3):
                        sheet.putpixel((cx + x * 3 + dx, cy + y * 3 + dy), 255)
sheet.save("/tmp/font_sheet.png")
print("wrote host/font8x16.h")
